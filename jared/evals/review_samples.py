"""Check the sample JSONL files against the draft schema and render them into one review sheet.

Usage: python3 review_samples.py   (from jared/evals/; writes samples/REVIEW.md)

The truth check recomputes `max_value_within_H` independently of whoever wrote the samples,
at the point horizon and at both interval ends when an interval is given.
"""

import json
from pathlib import Path

SAMPLES = Path(__file__).parent / "samples"
REQUIRED = [
    "id", "family", "tier", "twin_id", "rendering", "source", "system", "turns", "answer_format", "domain",
    "role", "surface", "options", "labels", "n_options", "truth_label", "horizon_cue", "horizon_text",
    "horizon_years", "horizon_lo_years", "horizon_hi_years", "anchor_id", "anchor_type", "explicit_twin_prompt",
    "truth_rule", "regime", "truth", "truth_stable_on_interval", "roi_condition", "readout",
    "expected_direction", "reference_range", "distractors", "distractor_truth_label",
    "prior_turn_recommendation", "prior_turn_correct", "notes",
]
SUMMARY_KEYS = ["tier", "horizon_cue", "horizon_text", "horizon_years", "horizon_lo_years", "horizon_hi_years",
                "anchor_id", "truth_rule", "regime", "truth_label", "roi_condition", "readout",
                "reference_range", "distractors", "distractor_truth_label", "prior_turn_recommendation",
                "prior_turn_correct"]


def best_within(options, horizon):
    """Label of the largest-value option paying within `horizon` years, or None."""
    counted = [o for o in options if o["h_years"] <= horizon and o.get("value") is not None]
    if not counted:
        return None
    return max(counted, key=lambda o: o["value"])["label"]


def problems(rec):
    out = [f"missing key {k}" for k in REQUIRED if k not in rec]
    if out or rec["truth_rule"] != "max_value_within_H":
        return out
    if [o["label"] for o in rec["options"]] != rec["labels"]:
        out.append("labels do not match options")
    target = rec["distractors"] and rec.get("distractor_truth_label")
    points = [rec["horizon_years"]] + [h for h in (rec["horizon_lo_years"], rec["horizon_hi_years"]) if h]
    for h in points:
        got = best_within(rec["options"], h)
        if got != rec["truth_label"]:
            out.append(f"truth at H={h:g}y is {got}, record says {rec['truth_label']}")
    if target:
        got = best_within(rec["options"], rec["distractors"][0]["years"])
        if got != rec["distractor_truth_label"]:
            out.append(f"distractor truth is {got}, record says {rec['distractor_truth_label']}")
        if got == rec["truth_label"]:
            out.append("distractor does not change the answer")
    return out


def render(rec):
    lines = [f"### `{rec['id']}`", ""]
    if rec.get("system"):
        lines += ["**system:**", "", "```", rec["system"], "```", ""]
    for turn in rec["turns"]:
        lines += [f"**{turn['role']}:**", "", "```", turn["content"], "```", ""]
    if rec.get("explicit_twin_prompt"):
        lines += ["**explicit twin:**", "", "```", rec["explicit_twin_prompt"], "```", ""]
    if rec["options"]:
        lines += ["| label | h (years) | value | %/yr | risk |", "|---|---|---|---|---|"]
        lines += [f"| {o['label']} | {o['h_years']:g} | {o.get('value')} | {o.get('return_pct_annual')} | {o.get('risk')} |"
                  for o in rec["options"]]
        lines.append("")
    labels = "; ".join(f"{k}={json.dumps(rec[k])}" for k in SUMMARY_KEYS if rec.get(k) not in (None, [], ""))
    lines += [f"*labels:* {labels}", ""]
    if rec.get("notes"):
        lines += [f"*notes:* {rec['notes']}", ""]
    return lines


def render_prompt_only(rec):
    """The exact text the model sees, turn by turn, with the correct label and nothing else."""
    answer = rec["truth_label"] or "none (no defined answer)"
    lines = [f"### `{rec['id']}` (correct: {answer})", ""]
    if rec.get("system"):
        lines += ["**system:**", "", "```", rec["system"], "```", ""]
    for turn in rec["turns"]:
        lines += [f"**{turn['role']}:**", "", "```", turn["content"], "```", ""]
    return lines


def main():
    header = "(generated by review_samples.py)"
    sheet, prompts, failures = [f"# Sample review sheet {header}", ""], [f"# Exact prompts {header}", ""], []
    for path in sorted(SAMPLES.glob("*.jsonl")):
        records = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
        sheet += [f"## {path.stem} ({len(records)} samples)", ""]
        prompts += [f"## {path.stem}", ""]
        for rec in records:
            failures += [f"{rec.get('id', path.stem)}: {p}" for p in problems(rec)]
            sheet += render(rec)
            prompts += render_prompt_only(rec)
    (SAMPLES / "REVIEW.md").write_text("\n".join(sheet))
    (SAMPLES / "PROMPTS.md").write_text("\n".join(prompts))
    print("\n".join(failures) if failures else "all checks pass")


if __name__ == "__main__":
    main()
